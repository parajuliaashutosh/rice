#!/usr/bin/env bash
# Today's Bikram Sambat (Nepali) date for waybar (JSON) or hyprlock (--plain).
# Port of services/NepaliDate.qml from the quickshell bar on main: BS month lengths aren't
# formulaic, so they come from a table; we count days forward from a known anchor:
# 1976-04-13 AD = 2033 Baishakh 1 BS. Covers 2033–2101 BS.
#   nepali-date.sh            {"text": "१७ कार्तिक २०८३", "tooltip": "2083-07-17 BS"}
#   nepali-date.sh --plain    १७ कार्तिक २०८३
#   nepali-date.sh --plain 2026-11-02   (any AD date, for testing)

day="${2:-$(date +%F)}"
days=$(( ($(date -u -d "$day" +%s) - $(date -u -d 1976-04-13 +%s)) / 86400 ))

awk -v days="$days" -v mode="${1:-}" '
BEGIN {
    split("वैशाख जेठ असार साउन भदौ असोज कार्तिक मंसिर पुष माघ फागुन चैत", months, " ")
    split("० १ २ ३ ४ ५ ६ ७ ८ ९", digits, " ")
}
# table rows: year, then the length of months 1..12
NF == 13 { n++; for (i = 1; i <= 13; i++) t[n, i] = $i }
END {
    if (days < 0) exit 1
    for (r = 1; r <= n; r++)
        for (m = 1; m <= 12; m++) {
            len = t[r, m + 1]
            if (days < len) {
                y = t[r, 1]; d = days + 1
                text = np(d) " " months[m] " " np(y)
                if (mode == "--plain") print text
                else printf "{\"text\": \"%s\", \"tooltip\": \"%d-%02d-%02d BS\"}\n", text, y, m, d
                exit 0
            }
            days -= len
        }
    exit 1
}
